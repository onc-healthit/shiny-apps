require(maps)
state.fips<-read.table("data/stateFips.txt",colClasses="character",header=T,sep=",")
stData<-function(data,colors) {
  stMap<-function(data,state){
    map("state",region=c(state),
        col=colors[data[as.numeric(rownames(state.fips[state.fips$state==state,]))]],
        fill=T,add=T,lty=0,resolution=0,mar=c(0,0,0,0))
  }
  stMap(data,'Alabama')
  stMap(data,'Arizona')
  stMap(data,'Arkansas')
